const TR_DECADE = { 1970: '’ler', 1980: '’ler', 1990: '’lar', 2000: '’ler', 2010: '’lar' };

function t(key, vars) {
  const lang = (window.Settings && Settings.get('lang')) || 'de';
  let s = (I18N[lang] && I18N[lang][key]) ?? I18N.en[key] ?? I18N.de[key] ?? key;
  if (vars) {
    for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  }
  if (key === 'decade' && lang === 'tr' && vars) s = s.replace('{suf}', TR_DECADE[vars.d] || '’ler');
  return s;
}

function langInfo(code) { return LANGS.find(l => l.code === code) || LANGS[0]; }

function detectLang() {
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || 'de';
  const l = nav.toLowerCase();
  if (l.startsWith('zh')) return (l.includes('tw') || l.includes('hk') || l.includes('hant')) ? 'zht' : 'zh';
  const short = l.slice(0, 2);
  return LANGS.some(x => x.code === short) ? short : 'de';
}

